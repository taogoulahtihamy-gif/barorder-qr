export function t(key, locale = 'fr') {
  if (locale === 'en') return key;
  return fr[key] || key;
}

export function useLocale() {
  const [locale, setLocale] = useState(() => localStorage.getItem('locale') || 'fr');

  useEffect(() => {
    localStorage.setItem('locale', locale);
  }, [locale]);

  const toggleLanguage = () => {
    setLocale((prev) => (prev === 'fr' ? 'en' : 'fr'));
  };

  return { locale, setLocale, toggleLanguage, t: (key) => t(key, locale) };
}

export default fr;
